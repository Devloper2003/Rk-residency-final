#!/usr/bin/env node
/**
 * Patch pdfkit's STANDARD_FONTS to load AFM data from an in-memory global
 * instead of using fs.readFileSync(__dirname + '/data/X.afm').
 *
 * Why: On Vercel's serverless runtime, the `data/` directory of the pdfkit
 * package is NOT bundled (tree-shaken), so `fs.readFileSync` throws ENOENT.
 *
 * This script does two things:
 *   1. Generates `src/lib/pdfkit-fonts.ts` — all 14 AFM files embedded as
 *      a TypeScript module so they're bundled as JS code (not data files).
 *   2. Patches `node_modules/pdfkit/js/pdfkit.js` so each
 *      `fs.readFileSync(__dirname + '/data/X.afm', 'utf8')` call is wrapped:
 *      `(globalThis.__RK_PDFKIT_FONTS__ && globalThis.__RK_PDFKIT_FONTS__['X']) || fs.readFileSync(...)`
 *      At runtime, our route sets `globalThis.__RK_PDFKIT_FONTS__` from the
 *      bundled AFM_FONTS map, so the global lookup succeeds and the
 *      fs.readFileSync fallback is never reached.
 *
 * Run via `postinstall` and `prebuild` hooks in package.json.
 */

const { readFileSync, readdirSync, writeFileSync, existsSync } = require("fs");
const { join } = require("path");

const ROOT = process.cwd();
const FONTS_DIR = join(ROOT, "node_modules/pdfkit/js/data");
const PDFKIT_JS = join(ROOT, "node_modules/pdfkit/js/pdfkit.js");
const OUTPUT_TS = join(ROOT, "src/lib/pdfkit-fonts.ts");

if (!existsSync(FONTS_DIR)) {
  console.log("[patch-pdfkit] pdfkit data dir not found, skipping.");
  process.exit(0);
}

// ─── Step 1: Generate src/lib/pdfkit-fonts.ts ────────────────────────
const fonts = readdirSync(FONTS_DIR).filter(f => f.endsWith(".afm"));
let tsOut = `// AUTO-GENERATED by scripts/patch-pdfkit-fonts.cjs — do not edit.
// All pdfkit AFM font metrics embedded as strings so the Voucher/Invoice
// PDF route works on Vercel's serverless runtime where pdfkit's data
// directory is not bundled.

export const AFM_FONTS: Record<string, string> = {
`;
for (const file of fonts) {
  const fontName = file.replace(/\.afm$/, "");
  const content = readFileSync(join(FONTS_DIR, file), "utf8");
  tsOut += `  ${JSON.stringify(fontName)}: ${JSON.stringify(content)},\n`;
}
tsOut += `};

// Default fallback (Helvetica) for unknown font names.
export function getAfmFont(name: string): string | undefined {
  return AFM_FONTS[name] ?? AFM_FONTS["Helvetica"];
}
`;
writeFileSync(OUTPUT_TS, tsOut);
console.log(`[patch-pdfkit] Generated ${OUTPUT_TS} (${fonts.length} fonts, ${(tsOut.length / 1024).toFixed(1)} KB)`);

// ─── Step 2: Patch node_modules/pdfkit/js/pdfkit.js ──────────────────
const PATCH_MARKER = "// [PATCHED BY scripts/patch-pdfkit-fonts.cjs]";
let pdfkitSrc = readFileSync(PDFKIT_JS, "utf8");

if (pdfkitSrc.startsWith(PATCH_MARKER)) {
  console.log("[patch-pdfkit] pdfkit.js already patched, skipping.");
  process.exit(0);
}

// Wrap each fs.readFileSync(__dirname + '/data/X.afm', 'utf8') call with
// a global lookup first. The fs.readFileSync call is kept as a fallback
// so local dev (where __dirname/data/*.afm exists) still works.
let patchCount = 0;
pdfkitSrc = pdfkitSrc.replace(
  /fs\.readFileSync\(__dirname \+ '\/data\/([A-Za-z-]+)\.afm', 'utf8'\)/g,
  (match, fontName) => {
    patchCount++;
    return `(globalThis.__RK_PDFKIT_FONTS__ && globalThis.__RK_PDFKIT_FONTS__[${JSON.stringify(fontName)}]) || fs.readFileSync(__dirname + '/data/${fontName}.afm', 'utf8')`;
  }
);

if (patchCount === 0) {
  console.error("[patch-pdfkit] No fs.readFileSync calls found to patch — aborting.");
  process.exit(1);
}

// Add patch marker as a comment at the very top of the file.
pdfkitSrc = PATCH_MARKER + "\n" + pdfkitSrc;

writeFileSync(PDFKIT_JS, pdfkitSrc);
console.log(`[patch-pdfkit] Patched ${PDFKIT_JS} (${patchCount} font calls wrapped, ${pdfkitSrc.length} bytes)`);
